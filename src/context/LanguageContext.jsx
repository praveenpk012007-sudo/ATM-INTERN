// Deep merge recursive helper to ensure seamless fallback to English for any key in any language
function deepMerge(target, source) {
  const output = { ...target };
  if (source && typeof source === 'object') {
    Object.keys(source).forEach(key => {
      if (source[key] && typeof source[key] === 'object' && !Array.isArray(source[key])) {
        output[key] = deepMerge(target[key] || {}, source[key]);
      } else if (source[key] !== undefined) {
        output[key] = source[key];
      }
    });
  }
  return output;
}

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try {
      return localStorage.getItem('cybereye_lang') || 'en';
    } catch (e) {
      return 'en';
    }
  });

  const [fontScale, setFontScale] = useState(() => {
    try {
      return localStorage.getItem('cybereye_fontscale') || 'normal';
    } catch (e) {
      return 'normal';
    }
  });

  const changeLanguage = (newLang) => {
    setLang(newLang);
    try {
      localStorage.setItem('cybereye_lang', newLang);
    } catch (e) {}
  };

  const changeFontScale = (scale) => {
    setFontScale(scale);
    try {
      localStorage.setItem('cybereye_fontscale', scale);
    } catch (e) {}
  };

  // Apply font scale to document root
  useEffect(() => {
    const root = document.documentElement;
    if (fontScale === 'small') {
      root.style.fontSize = '14px';
    } else if (fontScale === 'large') {
      root.style.fontSize = '18px';
    } else {
      root.style.fontSize = '16px';
    }
  }, [fontScale]);

  // Merge selected language with English fallback so NO translation key is ever undefined
  const targetDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const t = deepMerge(TRANSLATIONS.en, targetDict);

  return (
    <LanguageContext.Provider value={{ lang, setLang: changeLanguage, fontScale, setFontScale: changeFontScale, t, INDIAN_LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider');
  return ctx;
}
